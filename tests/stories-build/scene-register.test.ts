/**
 * 场景注册表生成物契约测试（`src/gen/scene_register.g.ts`）。
 *
 * 一个文件三段导出，三个消费方各取一段，缺任一段都有消费方拿不到入口：
 * - `scenes`（宿主）：「名字 → 组件」表，键就是 `SYS.body.name`；
 * - 具名句柄（故事源）：`export const kitchen: UiHandle<"kitchen">`，
 *   与 `*.vue` 折叠出同一个名字；
 * - `SceneNameRegistry`（类型面）：`body: { name: "…" }` 拼错在类型期红。
 *
 * 另锚三条纪律：
 * - 与 `ui_register.g.ts` **物理隔离**：两张表各写一个文件、互不引用、互不合并。
 *   合并会让 `mount("map")` 挂到整个地图、`body: { name: "hub" }` 指到 HUD；
 * - 同一次扫描必得同一份文本（差量写盘靠这个）；
 * - 名字含 `-` 时不生成具名句柄（不是合法标识符），只走 `scenes` 表与字符串形态。
 *
 * `SceneNameRegistry` 这一段只有在 `@lingfan-engine/core` 里存在同名空接口时才对
 * 消费端可见——最后一条用例用一次真实的 tsc 编译锁住「不是静默落空」。
 */
import { execFileSync } from "node:child_process";
import { mkdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { fileURLToPath } from "node:url";
import { afterEach, describe, expect, it } from "vitest";
import { buildStories } from "@lingfan-engine/stories-build";
import {
  renderSceneRegister,
  scanSceneRegistry,
  type SceneFileEntry,
} from "../../packages/stories-build/src/scene/index.ts";

const BASE = fileURLToPath(new URL("./.tmp-scene-register/", import.meta.url));

afterEach(() => {
  rmSync(BASE, { recursive: true, force: true });
});

const entry = (name: string, file = `${name}.vue`): SceneFileEntry => ({
  name,
  file,
});

describe("scene_register.g.ts 渲染", () => {
  it("三段导出：宿主表 + 具名句柄 + 类型面登记处", () => {
    const text = renderSceneRegister([entry("kitchen")], "../scenes");
    expect(text).toContain("GENERATED by stories:build (scene-register)");
    expect(text).toContain(
      'import type { UiHandle } from "@lingfan-engine/editor";',
    );
    // 组件导入走相对路径（不写别名：别名会把生成物绑死在某个 tsconfig 上）
    expect(text).toContain(
      'import kitchenView from "../scenes/kitchen/kitchen.vue";',
    );
    // 宿主表：键是 SYS.body.name，值是组件
    expect(text).toContain("export const scenes: Record<string, unknown> = {");
    expect(text).toContain('  "kitchen": kitchenView,');
    // 具名句柄：与 *.vue 折叠出同一个 name 字面量
    expect(text).toContain(
      'export const kitchen: UiHandle<"kitchen"> = { face: "uis", name: "kitchen" };',
    );
    // 类型面：declare module 合并进词汇层的空接口
    expect(text).toContain('declare module "@lingfan-engine/core" {');
    expect(text).toContain("  interface SceneNameRegistry {");
    expect(text).toContain('    "kitchen": 1;');
    // 生成物以换行收尾（差量比较靠逐字节一致）
    expect(text.endsWith("}\n")).toBe(true);
  });

  it("空注册表：scenes 是空表、句柄段与类型面都整段省略", () => {
    const text = renderSceneRegister([], "../scenes");
    expect(text).toContain("export const scenes: Record<string, unknown> = {");
    expect(text).toContain("};");
    // 没有场景就不该出现任何具名句柄导出（否则宿主读到一个不存在的组件）
    expect(text).not.toContain("UiHandle<");
    // 类型面同理整段省略：一段空登记处一个名字也登记不了——不必多写一段
    expect(text).not.toContain("SceneNameRegistry");
  });

  it("名字含 `-`：进 scenes 表与类型面，但不生成具名句柄（不是合法标识符）", () => {
    const text = renderSceneRegister([entry("room-kitchen")], "../scenes");
    expect(text).toContain(
      'import room_kitchenView from "../scenes/room-kitchen/room-kitchen.vue";',
    );
    expect(text).toContain('  "room-kitchen": room_kitchenView,');
    expect(text).toContain('    "room-kitchen": 1;');
    // 具名句柄段整段不出现：`export const room-kitchen` 是语法错误
    expect(text).not.toContain("UiHandle<");
    expect(text).not.toContain("export const room");
  });

  it("逐字节确定：同一份扫描结果渲染两次完全一致（差量写盘的前提）", () => {
    const entries = [entry("forest"), entry("kitchen"), entry("room-kitchen")];
    expect(renderSceneRegister(entries, "../scenes")).toBe(
      renderSceneRegister(entries, "../scenes"),
    );
    // 顺序即扫描顺序（扫描已按码点排好），渲染器不再排序——这里锚住「不重排」
    const text = renderSceneRegister(entries, "../scenes");
    expect(text.indexOf('"forest"')).toBeLessThan(text.indexOf('"kitchen"'));
    expect(text.indexOf('"kitchen"')).toBeLessThan(
      text.indexOf('"room-kitchen"'),
    );
  });

  it("绑定名去重：两个名字归一到同一标识符时不会撞车", () => {
    // `a-b` 与 `a_b` 都归一成 `a_bView`——第二个必须另起名字，否则重复声明
    const text = renderSceneRegister([entry("a-b"), entry("a_b")], "../scenes");
    expect(text).toContain('import a_bView from "../scenes/a-b/a-b.vue";');
    expect(text).toContain('import a_bView2 from "../scenes/a_b/a_b.vue";');
  });
});

describe("scene_register.g.ts 与 ui_register.g.ts 物理隔离", () => {
  it("两张表各写一个文件：名字互不引用", () => {
    const sceneText = renderSceneRegister([entry("kitchen")], "../scenes");
    // 场景生成物不提 uis / UiNameRegistry（合并就会让 mount 挂到身体组件上）
    expect(sceneText).not.toContain("export const uis");
    expect(sceneText).not.toContain("UiNameRegistry");
    // 反过来由 ui 注册表的用例负责（那边已锚住不含 SceneNameRegistry）
    expect(sceneText).toContain("export const scenes");
    expect(sceneText).toContain("SceneNameRegistry");
  });
});

describe("scanSceneRegistry：目录扫描", () => {
  it("只认 scenes/<名>/<名>.<组件扩展名>，按码点排序", () => {
    const root = join(BASE, "scan");
    const files = [
      "scenes/kitchen/kitchen.vue",
      "scenes/forest/forest.tsx",
      "scenes/hall/hall.ts",
    ];
    for (const rel of files) {
      const path = join(root, rel);
      mkdirSync(join(path, ".."), { recursive: true });
      writeFileSync(path, "");
    }
    // 干扰项：文件名 ≠ 目录名、非组件扩展名、隐藏目录
    mkdirSync(join(root, "scenes/kitchen"), { recursive: true });
    writeFileSync(join(root, "scenes/kitchen/other.vue"), "");
    writeFileSync(join(root, "scenes/kitchen/kitchen.svg"), "");
    mkdirSync(join(root, "scenes/.hidden"), { recursive: true });
    writeFileSync(join(root, "scenes/.hidden/.hidden.vue"), "");

    expect(scanSceneRegistry(join(root, "scenes"))).toEqual([
      { name: "forest", file: "forest.tsx" },
      { name: "hall", file: "hall.ts" },
      { name: "kitchen", file: "kitchen.vue" },
    ]);
  });

  it("目录不存在 ⇒ 空表（没场景的工程不该红）", () => {
    expect(scanSceneRegistry(join(BASE, "missing"))).toEqual([]);
  });
});

describe("整链：构建产出 scene_register.g.ts", () => {
  const config = (folders: string[]): string =>
    `export const folders = ${JSON.stringify(folders)};\nexport const start = "start.ts";\n`;

  const MANIFEST = `{
  "formatVersion": 1,
  "name": "场景注册表工程",
  "entry": "start",
  "shell": { "orientation": "auto" }
}`;

  const START = [
    'import { script } from "@lingfan-engine/editor";',
    "const { say } = script;",
    "",
    "export default function start(): void {",
    '  say("开场");',
    "}",
    "",
  ].join("\n");

  function makeProject(name: string, scenes: readonly string[]): string {
    const root = join(BASE, name);
    const files: Record<string, string> = {
      "src/Stories.src/config.ts": config(["ch1"]),
      "src/Stories.src/ch1/start.ts": START,
      "Resources/project.json": MANIFEST,
    };
    for (const scene of scenes) {
      files[`src/scenes/${scene}/${scene}.vue`] =
        "<template><div /></template>\n";
    }
    for (const [rel, text] of Object.entries(files)) {
      const path = join(root, rel);
      mkdirSync(join(path, ".."), { recursive: true });
      writeFileSync(path, text);
    }
    return root;
  }

  it("有场景目录：生成物落在 gen/ 且内容与渲染器一致、路径相对不写别名", async () => {
    const root = makeProject("with-scenes", ["kitchen"]);
    const report = await buildStories(root);
    expect(report.added).toContain("src/gen/scene_register.g.ts");
    const written = readFileSync(
      join(root, "src/gen/scene_register.g.ts"),
      "utf8",
    );
    expect(written).toBe(renderSceneRegister([entry("kitchen")], "../scenes"));
    // 别名（`@/scenes`）不许出现在生成物里
    expect(written).not.toContain("@/");
  });

  it("有场景目录：ui_register.g.ts 同时产出且不含场景名（两张表不串号）", async () => {
    const root = makeProject("two-tables", ["kitchen"]);
    await buildStories(root);
    const uiWritten = readFileSync(
      join(root, "src/gen/ui_register.g.ts"),
      "utf8",
    );
    const sceneWritten = readFileSync(
      join(root, "src/gen/scene_register.g.ts"),
      "utf8",
    );
    expect(uiWritten).not.toContain("kitchen");
    expect(sceneWritten).not.toContain("export const uis");
  });

  it("没有场景目录：不产出 scene_register.g.ts（零场景不落空文件）", async () => {
    const root = makeProject("no-scenes", []);
    const report = await buildStories(root);
    expect(report.added).not.toContain("src/gen/scene_register.g.ts");
    expect(() =>
      readFileSync(join(root, "src/gen/scene_register.g.ts"), "utf8"),
    ).toThrow();
  });

  it("场景目录被删空：已入库的生成物随之删除（不留陈旧文件）", async () => {
    const root = makeProject("drop-scenes", ["kitchen"]);
    const first = await buildStories(root);
    expect(first.added).toContain("src/gen/scene_register.g.ts");
    // 删掉唯一的场景目录再构建：文件必须消失，否则宿主会挂一个已经没有实现的组件
    rmSync(join(root, "src/scenes/kitchen"), { recursive: true, force: true });
    const second = await buildStories(root);
    expect(second.removed).toContain("src/gen/scene_register.g.ts");
  });
});

describe("SceneNameRegistry 对消费端可见（不是静默落空）", () => {
  /**
   * 一次真实编译：生成物里那段 `declare module` 只有在 `@lingfan-engine/core`
   * 存在同名空接口时才合并得进去。接口缺席时 `keyof SceneNameRegistry` 会
   * `TS2304`，登记表等于没写——这条用例就是防这个的。
   */
  it("`KnownSceneName` 收窄到登记过的名字，未登记名在类型期被拒", () => {
    const root = join(BASE, "type-check");
    mkdirSync(root, { recursive: true });
    const register = join(root, "scene_register.g.ts");
    writeFileSync(
      register,
      renderSceneRegister([entry("kitchen")], "../scenes"),
    );
    mkdirSync(join(root, "scenes/kitchen"), { recursive: true });
    writeFileSync(
      join(root, "scenes/kitchen/kitchen.vue"),
      "<template><div /></template>\n",
    );
    const probe = join(root, "probe.ts");
    writeFileSync(
      probe,
      [
        'import type { KnownSceneName } from "@lingfan-engine/editor";',
        "",
        "// 登记过的名字可赋值",
        'export const ok: KnownSceneName = "kitchen";',
        "",
        "// 未登记的名字在类型期被拒（下面这行故意错，靠 tsc 的退出码断言）",
        'export const bad: KnownSceneName = "forest";',
        "",
      ].join("\n"),
    );

    const tsc = join(
      fileURLToPath(new URL("../..", import.meta.url)),
      "node_modules/typescript/bin/tsc",
    );
    // 走 `-p`：直接给文件路径会撞上仓根 tsconfig 的 TS5112
    const tsconfig = join(root, "tsconfig.json");
    writeFileSync(
      tsconfig,
      JSON.stringify(
        {
          compilerOptions: {
            strict: true,
            noEmit: true,
            module: "esnext",
            target: "esnext",
            moduleResolution: "bundler",
            allowImportingTsExtensions: true,
          },
          include: ["*.ts"],
        },
        null,
        2,
      ),
    );
    const run = (): { status: number; text: string } => {
      try {
        const text = execFileSync(
          process.execPath,
          [tsc, "--noEmit", "-p", tsconfig],
          { cwd: root, encoding: "utf8", stdio: "pipe" },
        );
        return { status: 0, text };
      } catch (error) {
        const failure = error as {
          status?: number;
          stdout?: string;
          stderr?: string;
        };
        return {
          status: failure.status ?? 1,
          text: `${failure.stdout ?? ""}${failure.stderr ?? ""}`,
        };
      }
    };

    const result = run();
    // 恰好一条错，且错在未登记名那一行——多一条就说明登记表落空了
    expect(result.text).toContain('"forest"');
    expect(result.text).not.toMatch(/TS2304/);
    expect(result.status).not.toBe(0);
  }, 120_000);
});
