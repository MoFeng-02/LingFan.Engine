/**
 * UI 注册表生成物契约测试。
 *
 * 一个文件三段导出，三个消费方各取一段，缺任一段都有消费方拿不到入口：
 * - `uis`（宿主）：「名字 → 组件」表，键就是 `SYS.mounts` 里的名字；
 * - 具名句柄（故事源）：`export const hub: UiHandle<"hub">`，与 `*.vue` 折叠出同一个名字；
 * - `UiNameRegistry`（类型面）：`mount("…")` 拼错名字在类型期红。
 *
 * 另锚两条生成物纪律：同一次扫描必得同一份文本（差量写盘靠这个），
 * 以及名字含 `-` 时**不生成**具名句柄（不是合法标识符）而只走 `uis` 表与字符串形态。
 */
import { mkdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { fileURLToPath } from "node:url";
import { afterEach, describe, expect, it } from "vitest";
import { buildStories } from "@lingfan-engine/stories-build";
import {
  renderUiRegister,
  type UiFileEntry,
} from "../../packages/stories-build/src/ui/index.ts";

const BASE = fileURLToPath(new URL("./.tmp-ui-register/", import.meta.url));

afterEach(() => {
  rmSync(BASE, { recursive: true, force: true });
});

const entry = (name: string, file = `${name}.vue`): UiFileEntry => ({
  name,
  file,
});

describe("ui_register.g.ts 渲染", () => {
  it("三段导出：宿主表 + 具名句柄 + 类型面登记处", () => {
    const text = renderUiRegister([entry("hub")], "../ui");
    expect(text).toContain("GENERATED by stories:build");
    expect(text).toContain(
      'import type { UiHandle } from "@lingfan-engine/editor";',
    );
    // 组件导入走相对路径（不写别名：别名会把生成物绑死在某个 tsconfig 上）
    expect(text).toContain('import hubView from "../ui/hub/hub.vue";');
    // 宿主表：键是 SYS.mounts 里的名字，值是组件
    expect(text).toContain("export const uis: Record<string, unknown> = {");
    expect(text).toContain('  "hub": hubView,');
    // 具名句柄：与 *.vue 折叠出同一个 name 字面量
    expect(text).toContain(
      'export const hub: UiHandle<"hub"> = { face: "uis", name: "hub" };',
    );
    // 类型面：declare module 合并进词汇层的空接口
    expect(text).toContain('declare module "@lingfan-engine/editor" {');
    expect(text).toContain("  interface UiNameRegistry {");
    expect(text).toContain('    "hub": 1;');
    // 生成物以换行收尾（差量比较靠逐字节一致）
    expect(text.endsWith("}\n")).toBe(true);
  });

  it("空注册表：uis 是空表、句柄段与类型面都整段省略", () => {
    const text = renderUiRegister([], "../ui");
    expect(text).toContain("export const uis: Record<string, unknown> = {");
    expect(text).toContain("};");
    // 没有 UI 就不该出现任何具名句柄导出（否则宿主读到一个不存在的组件）
    expect(text).not.toContain("UiHandle<");
    // 类型面同理整段省略：空接口的 `declare module "@lingfan-engine/editor"` 会让
    // 没有 editor 依赖的工程（骨架层就不带）解析不到模块，而它一个名字也登记不了
    expect(text).not.toContain("UiNameRegistry");
  });

  it("名字含 `-`：进 uis 表与类型面，但不生成具名句柄（不是合法标识符）", () => {
    const text = renderUiRegister([entry("save-panel")], "../ui");
    expect(text).toContain(
      'import save_panelView from "../ui/save-panel/save-panel.vue";',
    );
    expect(text).toContain('  "save-panel": save_panelView,');
    expect(text).toContain('    "save-panel": 1;');
    // 具名句柄段整段不出现：`export const save-panel` 是语法错误
    expect(text).not.toContain("UiHandle<");
    expect(text).not.toContain("export const save");
  });

  it("逐字节确定：同一份扫描结果渲染两次完全一致（差量写盘的前提）", () => {
    const entries = [entry("bag"), entry("hub"), entry("save-panel")];
    expect(renderUiRegister(entries, "../ui")).toBe(
      renderUiRegister(entries, "../ui"),
    );
    // 顺序即扫描顺序（扫描已按码点排好），渲染器不再排序——这里锚住「不重排」
    const text = renderUiRegister(entries, "../ui");
    expect(text.indexOf('"bag"')).toBeLessThan(text.indexOf('"hub"'));
    expect(text.indexOf('"hub"')).toBeLessThan(text.indexOf('"save-panel"'));
  });

  it("绑定名去重：两个名字归一到同一标识符时不会撞车", () => {
    // `a-b` 与 `a_b` 都归一成 `a_bView`——第二个必须另起名字，否则重复声明
    const text = renderUiRegister([entry("a-b"), entry("a_b")], "../ui");
    expect(text).toContain('import a_bView from "../ui/a-b/a-b.vue";');
    expect(text).toContain('import a_bView2 from "../ui/a_b/a_b.vue";');
  });
});

describe("整链：构建产出 ui_register.g.ts", () => {
  const config = (folders: string[]): string =>
    `export const folders = ${JSON.stringify(folders)};\nexport const start = "start.ts";\n`;

  const MANIFEST = `{
  "formatVersion": 1,
  "name": "UI 注册表工程",
  "entry": "start",
  "shell": { "orientation": "auto" }
}`;

  it("有 UI 目录：生成物落在 gen/ 且内容与渲染器一致、路径相对不写别名", async () => {
    const root = join(BASE, "with-ui");
    const files: Record<string, string> = {
      "src/Stories.src/config.ts": config(["ch1"]),
      "src/Stories.src/ch1/start.ts": [
        'import { script } from "@lingfan-engine/editor";',
        "const { say } = script;",
        "",
        "export default function start(): void {",
        '  say("开场");',
        "}",
        "",
      ].join("\n"),
      "src/ui/hub/hub.vue": "<template><div /></template>\n",
      "Resources/project.json": MANIFEST,
    };
    for (const [rel, text] of Object.entries(files)) {
      const path = join(root, rel);
      mkdirSync(join(path, ".."), { recursive: true });
      writeFileSync(path, text);
    }
    const report = await buildStories(root);
    expect(report.added).toContain("src/gen/ui_register.g.ts");
    const written = readFileSync(
      join(root, "src/gen/ui_register.g.ts"),
      "utf8",
    );
    expect(written).toBe(renderUiRegister([entry("hub")], "../ui"));
    // 别名（`@/ui`）不许出现在生成物里
    expect(written).not.toContain("@/");
  });

  it("没有 UI 目录：生成物仍产出（空表），宿主与类型面都有形状可引", async () => {
    const root = join(BASE, "no-ui");
    const files: Record<string, string> = {
      "src/Stories.src/config.ts": config(["ch1"]),
      "src/Stories.src/ch1/start.ts": [
        'import { script } from "@lingfan-engine/editor";',
        "const { say } = script;",
        "",
        "export default function start(): void {",
        '  say("开场");',
        "}",
        "",
      ].join("\n"),
      "Resources/project.json": MANIFEST,
    };
    for (const [rel, text] of Object.entries(files)) {
      const path = join(root, rel);
      mkdirSync(join(path, ".."), { recursive: true });
      writeFileSync(path, text);
    }
    const report = await buildStories(root);
    expect(report.added).toContain("src/gen/ui_register.g.ts");
    const written = readFileSync(
      join(root, "src/gen/ui_register.g.ts"),
      "utf8",
    );
    expect(written).toBe(renderUiRegister([], "../ui"));
  });
});
