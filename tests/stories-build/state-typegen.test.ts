/**
 * state 类型面生成（形态 B gen 类型面）契约测试。
 *
 * 契约口径（界面规范 对应章节类型面分流 / 对应章节生成四处 / 对应章节 ambient 桥）：
 * buildStories 恒产出 `Stories.src/gen/state.gen.d.ts`：从 config 求值合并树
 * （形态 A state 导出 / 形态 B define 累积，二选一）渲染精确 `StoryState`——
 * descriptor 的 type 槽位按形状取精确类型（原生标量 / 单元素数组 leaf /
 * 多元素数组并集（成员可含 null）/ 枚举引用），枚举标识符从 config.ts 与模块层
 * 源文按点路径回收为 `import type`（相对层级按生成物目录改写，并集成员按下标
 * 配对），回收不到则回退成员值内联联合；键与枚举成员排序去重，同输入逐字节同
 * 输出；差量写盘与 stories.gen.d.ts 同一规则（新增/更新分开计，内容不变不写）。
 *
 * 五类覆盖（内部规约 对应章节 测试纪律）：①拟态用户（形态 B 全形状/形态 A/自定义根名 ambient 桥）
 * ②故意错误（不可识别 descriptor type fail-closed 且不落盘）③不变量（二进制稳定/差量）
 * ④边界（空树 Record<string, never>）⑤回归锚定（import 改写与联合回退的逐字节契约）。
 *
 * 白盒为零：全部走公共入口 buildStories（内部规约 公共 API 走 @lingfan/*）。
 */
import { existsSync, mkdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { fileURLToPath } from "node:url";
import { afterEach, describe, expect, it } from "vitest";
import { buildStories } from "@lingfan/stories-build";
// typegen 域内部单元（与 typegen.test.ts 同口径的深导入先例）：default 导入收集
// 在构建链上不可达（Stories.src 内 default 导出 = 故事文件，源发现拒收），直测收集器。
import { collectEnumTypeSlots } from "../../packages/stories-build/src/typegen";

const BASE = fileURLToPath(new URL("./.tmp-state-typegen/", import.meta.url));

afterEach(() => {
  rmSync(BASE, { recursive: true, force: true });
});

function makeProject(name: string, files: Record<string, string>): string {
  const root = join(BASE, name);
  for (const [rel, text] of Object.entries(files)) {
    const path = join(root, rel);
    mkdirSync(join(path, ".."), { recursive: true });
    writeFileSync(path, text);
  }
  return root;
}

const config = (folders: string[], start = "start.ts"): string =>
  `export const folders = ${JSON.stringify(folders)};\nexport const start = ${JSON.stringify(start)};\n`;

const MANIFEST = `{
  "formatVersion": 1,
  "name": "state 类型面工程",
  "entry": "start",
  "shell": { "orientation": "auto" }
}`;

const WORDS = `import { script } from "@lingfan/editor";
const { say } = script;

`;

const story = (name: string, body: string): string =>
  `${WORDS}export default function ${name}(): void {\n${body}\n}\n`;

const SEX_LIB = `export enum Sex {\n  Male = "male",\n  Female = "female",\n}\n`;

const STATE_GEN_REL = "Stories.src/gen/state.gen.d.ts";

/** 生成物头注释（与 state-render 的 HEADER 逐字节同源；扩写口径见用户定案） */
const HEADER =
  "/* GENERATED by stories:build (state-typegen) — 构建期自动生成，手改会在下次构建被覆盖。\n" +
  "   state（支持自定义状态根名）为强类型产物，可直接以根名操作关键状态变量；\n" +
  "   运行期 define 动态注入的键不在本类型面。 */";

function readStateGen(root: string): string {
  return readFileSync(join(root, STATE_GEN_REL), "utf8");
}

describe("state.gen.d.ts · 形态 B define 合并树 → 精确 StoryState", () => {
  it("descriptor 全形状逐字节契约：原生/数组/枚举别名导入/缺省回退联合", async () => {
    const root = makeProject("form-b-shapes", {
      "Stories.src/lib/sex.ts": SEX_LIB,
      "Stories.src/config.ts":
        `import { Sex as Gender } from "./lib/sex";\n` +
        config(["ch1"]) +
        `define("player.gold", 100);\n` +
        `define("player.level", { type: "number", default: 1 });\n` +
        `define("player.sex", { type: Gender, default: Gender.Male });\n` +
        `define("player.name", { type: "string", default: "旅人" });\n` +
        `define("dice", { type: "number", default: 1 });\n` +
        `define("supplies", { type: ["string"], default: [] });\n` +
        `define("mood", { type: { Happy: "happy", Sad: "sad" }, default: "happy" });\n`,
      "Stories.src/ch1/start.ts": story(
        "start",
        `  state.player.gold += 20;\n  say("金币 {player.gold}");\n`,
      ),
      "Resources/project.json": MANIFEST,
    });
    const report = await buildStories(root);
    expect(report.columns).toBe(1);
    // 逐字节契约：键排序、枚举 import 按生成物目录改写相对层级（./lib/sex → ../lib/sex）、
    // 别名导入保留 as 形态、内联枚举对象（AST 回收不到标识符）回退成员值联合。
    expect(readStateGen(root)).toBe(
      `${HEADER}\n` +
        `\n` +
        `import type { Sex as Gender } from "../lib/sex";\n` +
        `\n` +
        `export type StoryState = {\n` +
        `  "dice": number;\n` +
        `  "mood": "happy" | "sad";\n` +
        `  "player": {\n` +
        `    "gold": number;\n` +
        `    "level": number;\n` +
        `    "name": string;\n` +
        `    "sex": Gender;\n` +
        `  };\n` +
        `  "supplies": string[];\n` +
        `};\n`,
    );
  });

  it("形态 A state 导出同链路：枚举相对导入的 type 槽位同样生成 import", async () => {
    const root = makeProject("form-a-enum", {
      "Stories.src/lib/sex.ts": SEX_LIB,
      "Stories.src/config.ts":
        `import { Sex } from "./lib/sex";\n` +
        config(["ch1"]) +
        `export const state = { player: { sex: { type: Sex, default: Sex.Female } } } as const;\n`,
      "Stories.src/ch1/start.ts": story(
        "start",
        `  say("form A 的 gen 面只看 config 求值树，故事体无关");\n`,
      ),
      "Resources/project.json": MANIFEST,
    });
    await buildStories(root);
    expect(readStateGen(root)).toBe(
      `${HEADER}\n` +
        `\n` +
        `import type { Sex } from "../lib/sex";\n` +
        `\n` +
        `export type StoryState = {\n` +
        `  "player": {\n` +
        `    "sex": Sex;\n` +
        `  };\n` +
        `};\n`,
    );
  });

  it("default 导入的枚举：生成默认导入形态的 import type（收集器直测——Stories.src 内 default 导出即故事，构建链覆盖不到）", () => {
    const slots = collectEnumTypeSlots(
      `import Sex from "./lib/gender";\n` +
        `define("tone", { type: Sex, default: Sex.Male });\n`,
    );
    const slot = slots.get("tone");
    expect(slot).toEqual([
      {
        localName: "Sex",
        importedName: "default",
        source: "./lib/gender",
      },
    ]);
  });

  it("并集成员的枚举标识符按下标回收（收集器直测）", () => {
    const slots = collectEnumTypeSlots(
      `import { Sex } from "./lib/sex";\n` +
        `import { Lv } from "./lib/level";\n` +
        `define("hp", { type: ["number", Sex, null, Lv], default: null });\n`,
    );
    expect(slots.get("hp")).toEqual([
      { localName: "Sex", importedName: "Sex", source: "./lib/sex", memberIndex: 1 },
      { localName: "Lv", importedName: "Lv", source: "./lib/level", memberIndex: 3 },
    ]);
  });

  it("并集 type 槽位逐字节契约：枚举引用按成员下标配对、作者序保序、嵌套并集与内联枚举数组", async () => {
    const root = makeProject("union-shapes", {
      "Stories.src/lib/sex.ts": SEX_LIB,
      "Stories.src/config.ts":
        `import { Sex as Gender } from "./lib/sex";\n` +
        config(["ch1"]) +
        `define("hp", { type: ["number", Gender, null], default: null });\n` +
        `define("grade", { type: [null, "number", null], default: null });\n` +
        `define("span", { type: [["number", "string"], null], default: null });\n` +
        `define("team", { type: [Gender], default: [] });\n`,
      "Stories.src/ch1/start.ts": story(
        "start",
        `  say("并集成员按作者序渲染，回收槽位按下标配对");\n`,
      ),
      "Resources/project.json": MANIFEST,
    });
    await buildStories(root);
    expect(readStateGen(root)).toBe(
      `${HEADER}\n` +
        `\n` +
        `import type { Sex as Gender } from "../lib/sex";\n` +
        `\n` +
        `export type StoryState = {\n` +
        `  "grade": null | number;\n` +
        `  "hp": number | Gender | null;\n` +
        `  "span": number | string | null;\n` +
        `  "team": ("female" | "male")[];\n` +
        `};\n`,
    );
  });

  it("形态 A 并集同链路：as const 元组 + null 成员的枚举引用同样生成 import", async () => {
    const root = makeProject("union-form-a", {
      "Stories.src/lib/sex.ts": SEX_LIB,
      "Stories.src/config.ts":
        `import { Sex } from "./lib/sex";\n` +
        config(["ch1"]) +
        `export const state = {\n` +
        `  medal: { type: ["string", Sex, null] as const, default: null },\n` +
        `} as const;\n`,
      "Stories.src/ch1/start.ts": story(
        "start",
        `  say("形态 A 的并集走同一渲染器");\n`,
      ),
      "Resources/project.json": MANIFEST,
    });
    await buildStories(root);
    expect(readStateGen(root)).toBe(
      `${HEADER}\n` +
        `\n` +
        `import type { Sex } from "../lib/sex";\n` +
        `\n` +
        `export type StoryState = {\n` +
        `  "medal": string | Sex | null;\n` +
        `};\n`,
    );
  });

  it("空树恒产出：无 state 导出也无 define ⇒ Record<string, never>，桥永远有类型可引", async () => {
    const root = makeProject("empty-tree", {
      "Stories.src/config.ts": config(["ch1"]),
      "Stories.src/ch1/start.ts": story("start", `  say("hello");\n`),
      "Resources/project.json": MANIFEST,
    });
    const first = await buildStories(root);
    expect(first.added).toContain(STATE_GEN_REL);
    expect(readStateGen(root)).toBe(
      `${HEADER}\n` +
        `\n` +
        `export type StoryState = Record<string, never>;\n`,
    );
  });

  it("差量与幂等：改 type ⇒ updated；不变 ⇒ 第三跑 added/updated 均不含", async () => {
    const root = makeProject("delta", {
      "Stories.src/config.ts":
        config(["ch1"]) + `define("score", { type: "number", default: 0 });\n`,
      "Stories.src/ch1/start.ts": story("start", `  say("hello");\n`),
      "Resources/project.json": MANIFEST,
    });
    const first = await buildStories(root);
    expect(first.added).toContain(STATE_GEN_REL);
    expect(readStateGen(root)).toContain(`"score": number;`);

    // 改 type：内容随之变，差量记为 updated（且只此一条类型面变化）。
    writeFileSync(
      join(root, "Stories.src/config.ts"),
      config(["ch1"]) + `define("score", { type: "string", default: "0" });\n`,
    );
    const second = await buildStories(root);
    expect(second.updated).toContain(STATE_GEN_REL);
    expect(second.added).not.toContain(STATE_GEN_REL);
    expect(readStateGen(root)).toContain(`"score": string;`);

    // 字节级幂等：同输入再跑，零新增零更新。
    const third = await buildStories(root);
    expect(third.added).not.toContain(STATE_GEN_REL);
    expect(third.updated).not.toContain(STATE_GEN_REL);
  });

  it("fail-closed：不可识别 descriptor type ⇒ 构建抛错且不落任何生成物", async () => {
    const root = makeProject("bad-descriptor", {
      "Stories.src/config.ts":
        config(["ch1"]) + `define("weird", { type: "carrot", default: 1 });\n`,
      "Stories.src/ch1/start.ts": story("start", `  say("hello");\n`),
      "Resources/project.json": MANIFEST,
    });
    await expect(buildStories(root)).rejects.toThrow(/无法识别的 descriptor type/);
    expect(existsSync(join(root, STATE_GEN_REL))).toBe(false);
    expect(existsSync(join(root, "Stories.src/gen/stories.gen.d.ts"))).toBe(false);
  });
});

describe("state.gen.d.ts · 自定义状态根（ambient 桥）", () => {
  it("declare global { var hero: StoryState } 被按名识别：按 hero 剥根编译", async () => {
    const root = makeProject("ambient-root", {
      // 桥文件形态：类型本地别名 + ambient 全局根（export/export {} 使其成为模块）。
      "Stories.src/lib/root.ts":
        `export type StoryState = { player: { gold: number } };\n` +
        `declare global {\n  var hero: StoryState;\n}\nexport {};\n`,
      "Stories.src/config.ts":
        config(["ch1"]) + `define("player.gold", 100);\n`,
      "Stories.src/ch1/start.ts": story(
        "start",
        `  hero.player.gold += 10;\n  say("金币 {player.gold}");\n`,
      ),
      "Resources/project.json": MANIFEST,
    });
    const report = await buildStories(root);
    // 识别成功 ⇒ hero.player.gold 按根 hero 剥成状态引用（识别失败会回退 "state"，
    // hero 变未知标识符而 fail-closed，构建不可能通过）。
    expect(report.columns).toBe(1);
    const project = JSON.parse(
      readFileSync(join(root, "Resources/project.json"), "utf8"),
    ) as { defines?: Record<string, unknown> };
    expect(project.defines).toMatchObject({ "player.gold": 100 });
  });
});
