/**
 * UI 注册表生成物的渲染器（`src/gen/ui_register.g.ts` 全文）。
 *
 * 一个文件三段导出，三个消费方各取一段：
 * 1. `uis` —— 「名字 → 组件」表，宿主按 `SYS.mounts` 的键去查，查到就渲染；
 * 2. 具名句柄 `hub` —— 故事源按具名导入直接用，不依赖 `*.vue` 的 ambient 声明；
 * 3. `declare module "@lingfan-engine/editor"` 的 `UiNameRegistry` —— 类型面，
 *    `mount("…")` 的字符串名字写错在类型期就红。
 *
 * 名字的唯一来源是 `ui/<名>/` 目录名（`scanUiRegistry`），生成物里不再归一、
 * 不再排序（扫描已排好），同一次扫描必得同一份文本 —— 差量写盘靠这一点。
 *
 * 注意具名句柄只对**能当标识符的名字**生成：UI 名允许 `-`（`save-panel` 合法），
 * 那种名字没法做导出名，只能走 `uis` 表与字符串形态。这条规则写在文件头注释里，
 * 免得作者以为生成器漏了一个。
 */
import type { UiFileEntry } from "./ui-registry.ts";

/** TS 标识符形态（UI 名允许 `-`，那种名字没有具名句柄） */
const IDENTIFIER = /^[A-Za-z_$][A-Za-z0-9_$]*$/;

/**
 * 渲染 `ui_register.g.ts` 全文。
 *
 * @param entries 扫描出的 UI 条目（已按名字排好序）
 * @param uiRelFromGenerated 从生成物目录到 UI 根目录的相对路径（posix，无尾斜杠），
 *   如 `"../ui"`。生成物里一律写相对路径，不写别名 —— 别名是创作期便利，
 *   产物与生成物里出现别名就会把宿主绑死在某个 tsconfig 上。
 */
export function renderUiRegister(
  entries: readonly UiFileEntry[],
  uiRelFromGenerated: string,
): string {
  const lines: string[] = [];
  const bindings = bindingsOf(entries);
  const handleEntries = entries.filter((entry) => IDENTIFIER.test(entry.name));
  lines.push(
    "/* GENERATED by stories:build (ui-register) — 手改会在下次构建被覆盖 */",
  );
  // 没有 UI 的工程不写这一行：未使用的类型导入会让消费工程的 `noUnusedLocals` 直接红
  if (handleEntries.length > 0) {
    lines.push('import type { UiHandle } from "@lingfan-engine/editor";');
  }
  for (const entry of entries) {
    lines.push(
      `import ${bindings.get(entry.name)} from ${JSON.stringify(`${uiRelFromGenerated}/${entry.name}/${entry.file}`)};`,
    );
  }
  lines.push("");
  lines.push(
    "/** 宿主用：「名字 → 组件」表。键就是 `SYS.mounts` 里的名字，不需要再归一。 */",
  );
  lines.push("export const uis: Record<string, unknown> = {");
  for (const entry of entries) {
    lines.push(`  ${JSON.stringify(entry.name)}: ${bindings.get(entry.name)},`);
  }
  lines.push("};");

  if (handleEntries.length > 0) {
    lines.push("");
    lines.push(
      '/** 故事源用：具名句柄，与 `import hub from "…/hub.vue"` 折叠出同一个名字。 */',
    );
    for (const entry of handleEntries) {
      lines.push(
        `export const ${entry.name}: UiHandle<${JSON.stringify(entry.name)}> = { face: "uis", name: ${JSON.stringify(entry.name)} };`,
      );
    }
  }

  // 没有 UI 的工程到此为止：类型面登记处指向 `@lingfan-engine/editor`，
  // 而只用 `.story` 故事源的工程没有这个依赖（它是故事源 TS 层带进来的），
  // 空表里也没有任何名字可登记——多写一段只会让那种工程解析不到模块。
  if (entries.length === 0) return `${lines.join("\n")}\n`;

  lines.push("");
  lines.push(
    '/** UI 名的构建期登记处：`mount("…")` 引用了未登记的名字会在类型期报错。 */',
  );
  lines.push('declare module "@lingfan-engine/editor" {');
  lines.push("  interface UiNameRegistry {");
  for (const entry of entries) {
    lines.push(`    ${JSON.stringify(entry.name)}: 1;`);
  }
  lines.push("  }");
  lines.push("}");
  return `${lines.join("\n")}\n`;
}

/**
 * 每个 UI 的组件导入绑定名。
 *
 * 不能直接用 UI 名：具名句柄 `export const hub` 已经占住了那个标识符，
 * 同名的两个声明会重复；而且 UI 名允许 `-`（`save-panel` 合法），
 * 那种名字根本不能当标识符。所以统一加 `View` 后缀，非法字符换成 `_`，
 * 撞名再按出现次序加数字（同一次扫描结果稳定，文本才可差量比较）。
 */
function bindingsOf(
  entries: readonly UiFileEntry[],
): ReadonlyMap<string, string> {
  const taken = new Set<string>();
  const out = new Map<string, string>();
  for (const entry of entries) {
    const base = entry.name.replace(/[^A-Za-z0-9_$]/g, "_");
    const seed = /^[A-Za-z_$]/.test(base) ? base : `_${base}`;
    let candidate = `${seed}View`;
    for (let n = 2; taken.has(candidate); n += 1) {
      candidate = `${seed}View${n}`;
    }
    taken.add(candidate);
    out.set(entry.name, candidate);
  }
  return out;
}
