/**
 * StoryState 类型面渲染器（形态 B gen 类型面）。
 *
 * 输入 = config 求值合并树（形态 A state 树 / 形态 B define 树，与降维段同一棵）+
 * AST 侧回收的枚举 type 槽位（collectEnumTypeSlotsForBuild）。输出 =
 * `Stories.src/gen/state.gen.d.ts` 全文：嵌套对象字面量的 `export type StoryState = { … }`，
 * descriptor 叶按 type 槽位取精确类型——原生标量 / 单元素数组 leaf / 多元素数组并集 /
 * 枚举引用（import type）或内联字面量联合。
 *
 * 用法与注意事项：
 * - 渲染只吃「已过降维文法校验」的树（编排顺序保证：runStateSchemaPass 先行，文法
 *   违规在生成之前已 fail-closed）；未知形态按 unknown 兜底而不是猜测。
 * - 恒产出：工程未声明任何状态键时退化为 `Record<string, never>`，桥文件永远有类型
 *   可引（与 stories.gen.d.ts 空集合也落文件同思路）。
 * - 空分支不产键（与降维语义一致：空对象贡献零 defines）；键排序去重保证同输入
 *   逐字节同输出。
 */
import { posix } from "node:path";
import type { EnumTypeSlot } from "./state-enum-ast";

export interface StateTypegenInput {
  /** config 求值合并树（形态 A state / 形态 B defineTree，与降维段同一棵） */
  readonly tree: unknown;
  /** 点路径 → 枚举 type 槽位列表（直接槽位与并集成员槽位，collectEnumTypeSlotsForBuild 的结果） */
  readonly enumSlots: ReadonlyMap<string, EnumTypeSlot[]>;
  /** 生成物目录名（相对源根，如 "gen"）：import 说明符按它改写相对层级 */
  readonly generatedDir: string;
}

const HEADER = [
  "/* GENERATED by stories:build (state-typegen) — 构建期自动生成，手改会在下次构建被覆盖。",
  "   state（支持自定义状态根名）为强类型产物，可直接以根名操作关键状态变量；",
  "   运行期 define 动态注入的键不在本类型面。 */",
].join("\n");

const PRIMITIVE_TYPES = new Set(["number", "string", "boolean"]);

export function renderStateTypegen(input: StateTypegenInput): string {
  const used = new Map<string, EnumTypeSlot>();
  const body = renderValue(input.tree, "", 0, input.enumSlots, used);
  const lines: string[] = [HEADER, ""];
  const importLines = renderImports(used, input.generatedDir);
  if (importLines.length > 0) lines.push(...importLines, "");
  lines.push(`export type StoryState = ${body ?? "Record<string, never>"};`);
  return `${lines.join("\n")}\n`;
}

/** 渲染一个树节点；undefined = 空分支（调用方跳过该键，与降维「不产键」一致） */
function renderValue(
  value: unknown,
  path: string,
  depth: number,
  slots: ReadonlyMap<string, EnumTypeSlot[]>,
  used: Map<string, EnumTypeSlot>,
): string | undefined {
  if (isPlainObject(value)) {
    if ("type" in value || "default" in value) {
      return renderTypeSlot(value.type, path, slots, used);
    }
    return renderObject(value, path, depth, slots, used);
  }
  if (
    typeof value === "number" ||
    typeof value === "string" ||
    typeof value === "boolean"
  ) {
    return typeof value;
  }
  return "unknown";
}

function renderObject(
  obj: Record<string, unknown>,
  path: string,
  depth: number,
  slots: ReadonlyMap<string, EnumTypeSlot[]>,
  used: Map<string, EnumTypeSlot>,
): string | undefined {
  const lines: string[] = [];
  for (const key of Object.keys(obj).sort()) {
    const childPath = path === "" ? key : `${path}.${key}`;
    const rendered = renderValue(obj[key], childPath, depth + 1, slots, used);
    if (rendered === undefined) continue;
    lines.push(`${"  ".repeat(depth + 1)}${JSON.stringify(key)}: ${rendered};`);
  }
  if (lines.length === 0) return undefined;
  return `{\n${lines.join("\n")}\n${"  ".repeat(depth)}}`;
}

/** descriptor 的 type 槽位：原生名 / [leaf] 数组 / 多元素并集 / 枚举对象（引用或内联联合） */
function renderTypeSlot(
  type: unknown,
  path: string,
  slots: ReadonlyMap<string, EnumTypeSlot[]>,
  used: Map<string, EnumTypeSlot>,
): string {
  if (typeof type === "string" && PRIMITIVE_TYPES.has(type)) return type;
  if (Array.isArray(type)) {
    if (type.length >= 2) return renderUnionSlot(type, path, slots, used, true);
    if (type.length === 1) {
      return `${parenthesizeUnion(renderTypeSlot(type[0], path, slots, used))}[]`;
    }
    return "unknown";
  }
  if (isPlainObject(type)) {
    const slot = findSlot(path, undefined, slots);
    if (slot !== undefined) {
      used.set(slot.localName, slot);
      return slot.localName;
    }
    return renderEnumUnion(type);
  }
  return "unknown";
}

/**
 * 并集成员槽位渲染：成员按作者序取并集（保序 Set 去重，确定性由源序保证）。
 * 枚举成员优先走回收槽位（按成员下标配对）生成 import 引用，取不到则内联
 * 字面量联合；嵌套并集递归渲染但不回收枚举（内联回退）。
 */
function renderUnionSlot(
  members: readonly unknown[],
  path: string,
  slots: ReadonlyMap<string, EnumTypeSlot[]>,
  used: Map<string, EnumTypeSlot>,
  recoverEnums: boolean,
): string {
  const rendered: string[] = [];
  const seen = new Set<string>();
  const push = (text: string): void => {
    if (seen.has(text)) return;
    seen.add(text);
    rendered.push(text);
  };
  members.forEach((member, index) => {
    if (member === null) {
      push("null");
      return;
    }
    if (typeof member === "string" && PRIMITIVE_TYPES.has(member)) {
      push(member);
      return;
    }
    if (Array.isArray(member)) {
      if (member.length === 1) {
        push(`${parenthesizeUnion(renderTypeSlot(member[0], path, slots, used))}[]`);
        return;
      }
      push(renderUnionSlot(member, path, slots, used, false));
      return;
    }
    if (isPlainObject(member)) {
      const slot = recoverEnums ? findSlot(path, index, slots) : undefined;
      if (slot !== undefined) {
        used.set(slot.localName, slot);
        push(slot.localName);
        return;
      }
      push(renderEnumUnion(member));
      return;
    }
    push("unknown");
  });
  return rendered.length === 0 ? "unknown" : rendered.join(" | ");
}

/** 按路径与成员下标取回收槽位（memberIndex undefined = 直接 type 槽位） */
function findSlot(
  path: string,
  memberIndex: number | undefined,
  slots: ReadonlyMap<string, EnumTypeSlot[]>,
): EnumTypeSlot | undefined {
  return slots.get(path)?.find((slot) => slot.memberIndex === memberIndex);
}

/**
 * 数组位置包联合：TS 里 `A | B[]` 解析为 `A | (B[])`，叶是联合时必须
 * 括起来才是「联合元素的数组」（如内联枚举 leaf → `("a" | "b")[]`）。
 */
function parenthesizeUnion(rendered: string): string {
  return rendered.includes(" | ") ? `(${rendered})` : rendered;
}

/** 枚举成员值联合（字符串 JSON 引号、数字原样；排序 + 同值去重保证确定性） */
function renderEnumUnion(values: Record<string, unknown>): string {
  const rendered = new Set<string>();
  for (const value of Object.values(values)) {
    if (typeof value === "string") rendered.add(JSON.stringify(value));
    else if (typeof value === "number") rendered.add(String(value));
  }
  return rendered.size === 0 ? "unknown" : [...rendered].sort().join(" | ");
}

function renderImports(
  used: ReadonlyMap<string, EnumTypeSlot>,
  generatedDir: string,
): string[] {
  const bySource = new Map<string, EnumTypeSlot[]>();
  for (const slot of used.values()) {
    const list = bySource.get(slot.source) ?? [];
    list.push(slot);
    bySource.set(slot.source, list);
  }
  const lines: string[] = [];
  for (const source of [...bySource.keys()].sort()) {
    const specifier = JSON.stringify(rewriteSpecifier(source, generatedDir));
    const slots = bySource.get(source);
    if (slots === undefined) continue;
    for (const slot of slots.filter((s) => s.importedName === "default")) {
      lines.push(`import type ${slot.localName} from ${specifier};`);
    }
    const named = slots
      .filter((s) => s.importedName !== "default")
      .sort((a, b) => a.localName.localeCompare(b.localName))
      .map((s) =>
        s.importedName === s.localName
          ? s.localName
          : `${s.importedName} as ${s.localName}`,
      );
    if (named.length > 0) {
      lines.push(`import type { ${named.join(", ")} } from ${specifier};`);
    }
  }
  return lines;
}

/**
 * import 说明符改写：源根内相对路径（"./lib/enums"）按生成物目录换算相对层级
 * （"gen" → "../lib/enums"）；包导入原样保留。
 */
function rewriteSpecifier(source: string, generatedDir: string): string {
  if (!source.startsWith(".")) return source;
  const rel = posix.relative(generatedDir, posix.normalize(source));
  return rel.startsWith(".") ? rel : `./${rel}`;
}

function isPlainObject(value: unknown): value is Record<string, unknown> {
  return typeof value === "object" && value !== null && !Array.isArray(value);
}
