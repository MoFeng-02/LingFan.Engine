/**
 * 字符串排序判据：比较结果只由码元决定，与运行环境的语言无关。
 *
 * 为什么不用 `localeCompare`：它的结果来自 ICU 排序规则，随宿主默认 locale 变。
 * 同一份故事源码在中文开发机与英文构建机上会排出不同顺序，产物字节因此不同——
 * 这属于构建确定性缺口，不是测试期望问题。码元序没有这层隐含输入。
 *
 * 口径：逐位比 UTF-16 码元，短串在前。调用方一律走这里，不要各写一份比较器；
 * 数组自身的默认 `sort()` 与 `font-registry` 等处已是同一口径，故全仓排序语义统一。
 */

/** 字典序比较：只按码元定序，返回负数 / 0 / 正数（含代理对按码元而非码位） */
export function compareOrdinal(a: string, b: string): number {
  return a < b ? -1 : a > b ? 1 : 0;
}
